# Under a long skirt the whole body and hem bob and sway; only the shoes stay on the ground. Each frame: the body
# (bobbed, its hem swayed), the hand-drawn shoes for that step, and the arms' swing patches.
def _shift_rows(rows, y0, y1, dx):
    out = list(rows)
    for y in range(y0, y1 + 1):
        r = rows[y]
        out[y] = ('.' * dx + r[:len(r) - dx]) if dx > 0 else (r[-dx:] + '.' * (-dx)) if dx < 0 else r
    return out

