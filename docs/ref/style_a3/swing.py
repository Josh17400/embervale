def key_r(legs, dx, dy, back, front, head=None):
    upper = hero.R_UPPER if head is None else head + hero.R_UPPER[len(head):]
    parts = []
    if back:
        parts.append((back, 0, 0))
    parts += [(hero.R_SCAB, hero.OX, hero.OY + 26 + dy), (hero.R_LEGS[legs], hero.OX, hero.OY + 25),
              (upper, hero.OX + dx, hero.OY + dy), (front, 0, 0)]
    return layer(44, 44, *parts)


