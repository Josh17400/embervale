# ====================================================================== A3 additions (on A's proportions)
# --- secondary motion for the front walk: the cowlick lags the bob (it stretches on the down frames, squashes on the up)
def _tuft(frame, bob, x0=13):
    out = [list(r) for r in frame]
    if bob == 1:                       # the head dropped a row; the tip stays behind
        out[1][x0 + 1] = 'a'
    elif bob == -1:                    # the head rose a row; the tip flattens into the crown
        out[0][x0] = '.'
        out[0][x0 + 1] = '.'
        out[1][x0 + 1] = 'a'
    return [''.join(r) for r in out]


