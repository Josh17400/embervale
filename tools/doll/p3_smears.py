#!/usr/bin/env python3
# tools/doll/p3_smears.py: (P3 ART, B1) the sword's strike trails, written into rpg/art/doll/maps/fx/arc.pxm as the keys
# t1 t2 t3 (hits 1-3, the strike frame) in four facings. The old crescent (a1) closed ahead of the hand and, with a level
# blade, read as a drawn bow; a trail is a smear on the circle the tip runs round (centred on the fist, its radius the
# blade's reach), running BACK from the tip the way the blade came, widest at the tip (5 px, the outer third of the blade: core on the rim, body, edge)
# and thinning to a 1 px edge wisp at its tail: it never reaches ahead of the blade. Anchored on the fist (`anchor grip`),
# so one drawing serves the man and the woman. The geometry (each strike frame's grip and tip, from rpg_test --doll
# --limbs on the sword hero) is the table below; the sweep: +1 clockwise on screen (y down), -1 counter-clockwise.
# The game's live trail (art_fx.cpp steelSmear, View::drawSwingFx) paints the same smear from the frame's own anchors.
#   python tools/doll/p3_smears.py [--check]      (rewrites the block between the P3 SMEARS markers in arc.pxm)
import math, os, sys
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ARC = os.path.join(REPO, 'rpg', 'art', 'doll', 'maps', 'fx', 'arc.pxm')
SPAN = 85.0   # degrees of trail behind the tip
# (hit, facing): grip, tip (pivot-relative, the strike frame of sword.clip), sweep, layer
GEOM = {
    (1, 'R'): ((11, -17), (24, -4), +1, 'fxBack'), (1, 'L'): ((-14, -17), (-27, -4), -1, 'fxBack'),
    (1, 'D'): ((1, -8), (10, -1), -1, 'fx'),       (1, 'U'): ((-3, -10), (-16, -4), +1, 'fxBack'),
    (2, 'R'): ((11, -21), (24, -34), -1, 'fxBack'), (2, 'L'): ((-12, -21), (-25, -34), +1, 'fxBack'),
    (2, 'D'): ((1, -19), (14, -32), -1, 'fx'),     (2, 'U'): ((0, -21), (-6, -34), -1, 'fxBack'),
    (3, 'R'): ((14, -15), (27, -2), +1, 'fxBack'), (3, 'L'): ((-15, -15), (-28, -2), -1, 'fxBack'),
    (3, 'D'): ((-2, -11), (-2, 1), -1, 'fx'),      (3, 'U'): ((9, -15), (15, -2), +1, 'fxBack'),
}
BEGIN, END = '# ---- P3 SMEARS (generated by tools/doll/p3_smears.py: do not edit by hand)', '# ---- P3 SMEARS end'


def smear(tip, sweep, span=SPAN, wmax=5.0, stop=0.0):
    """cells {(x, y): char} relative to the fist: the trail behind the tip (A core on the rim, B body, C edge)"""
    tx, ty = tip
    r = math.hypot(tx, ty)
    ah = math.degrees(math.atan2(ty, tx))
    cells = {}
    R = int(r) + 2
    for y in range(-R, R + 1):
        for x in range(-R, R + 1):
            d = math.hypot(x, y)
            if d < 1:
                continue
            th = math.degrees(math.atan2(y, x))
            rel = ((th - ah) * sweep + 540.0) % 360.0 - 180.0   # 0 at the tip, negative behind it
            s = 1.0 + rel / span                                 # 0 the tail .. 1 the tip
            if s < 0 or s > 1.0 - stop:
                continue
            w = 1.0 + (wmax - 1.0) * s
            dd = r + 0.5 - d
            if dd < 0 or dd >= w:
                continue
            cells[(x, y)] = 'A' if dd < 1.2 and s > 0.25 else ('B' if dd < w - 1.2 and s > 0.12 else 'C')
    return cells


def block():
    out = [BEGIN,
           '# (P3 ART, B1) the strike trails t1-t3: see tools/doll/p3_smears.py (the a1 crescent stays for the frames that name it).']
    for (hit, fc), (g, t, sw, layer) in sorted(GEOM.items(), key=lambda kv: (kv[0][0], 'RDLU'.index(kv[0][1]))):
        c = smear((t[0] - g[0], t[1] - g[1]), sw)
        # never below the soles: the lowest row a pixel above them (the owner, 2026-10-23: the D crescent dropped under the feet)
        c = {k: v for k, v in c.items() if g[1] + k[1] <= -2}
        xs = [p[0] for p in c]; ys = [p[1] for p in c]
        x0, x1, y0, y1 = min(xs + [0]), max(xs + [0]), min(ys + [0]), max(ys + [0])
        out.append(f'view {fc} key t{hit} origin {-x0} {-y0} layer {layer} anchor grip')
        for y in range(y0, y1 + 1):
            out.append('|' + ''.join(c.get((x, y), '.') for x in range(x0, x1 + 1)))
        out.append('')
    out.append(END)
    return '\n'.join(out)


def main():
    s = open(ARC, encoding='utf-8').read()
    b = block()
    if BEGIN in s:
        i, j = s.index(BEGIN), s.index(END) + len(END)
        new = s[:i] + b + s[j:]
    else:
        new = s.rstrip('\n') + '\n\n' + b + '\n'
    if '--check' in sys.argv:
        sys.exit(0 if new == s else 1)
    if new != s:
        open(ARC, 'w', encoding='utf-8', newline='\n').write(new)
    print('p3_smears: arc.pxm', 'written' if new != s else 'unchanged')


if __name__ == '__main__':
    main()
