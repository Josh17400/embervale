#!/usr/bin/env python3
# tools/doll/p4_leather.py: (P4 ART, item 6e; D116) the leather gambeson reads as leather. A worn padded coat of LEATHER
# (the resolver's `leather-coat` flag: armour padded, armour band 1, not the T1 floor's jerkin) drew in the gambeson's buff
# quilt (cloth3; hers linen), so a LEATHER GAMBESON was a cream tunic beside the hero's own T1 floor jerkin. This tool ADDS,
# to rpg/art/doll/maps/armour/{man,woman}/padded.pxm and padded_hang.pxm, a re-cut of every view under `leather-coat`
# (never touching a drawn view): the SAME mask, origin, regions, build row, puts and marks (no outline, fit or bulk change:
# T1 stays slim and simple, the owner's rule), its pixels by rule:
#   - the coat's quilt (the file's own legend 5-9: his cloth3, her linen) becomes the wearer's leather, step for step
#     (6 -> g, 7 -> h, 8 -> i, 9 -> j): the quilt channels read as stitched leather panels; its edge (5) the leather's step 1,
#     not step 0 (a tan or black leather's step 0 is near-black for the boot against grass: on the coat it read as holes);
#   - the belt row (a body row of leather between the coat's outline) a step darker (j -> i, i -> h, h -> g), the buckle
#     kept, so the belt still parts from the hide;
#   - the front laced in rawhide (cloth3, the undyed buff: his 7 / 8, her C / D): facing D a criss-cross down the centre two
#     columns from under the collar to the belt (each crossing the buff's lit step, one step over the hide's lit plane, the
#     slit between them the leather's step 1); facing R / L a run of lace eyes one pixel inside the front edge; facing U
#     and the lying views no lace (the back of the coat, the body on the ground);
#   - the collar, the hem, metal and every other character kept.
#   - (P5 MARKS, decision 2) the lace crossings take N in the region plane (a view that has one; only '.' cells): a maker
#     people's coat laces in its dye band (FIX_BATCH_P5 3.3), a maker-less coat keeps the rawhide.
# Where the views go: a re-cut of a base view is `when leather-coat replace`, appended after every view of the file (so a
# file's own tier views still win where no leather re-cut of theirs exists: there is one for each); a re-cut of a `replace`
# view (`when C replace`) is `when leather-coat,C replace`, placed just BEFORE it (the first replacing view that holds wins);
# a re-cut of an overlay (`when C`) is `when leather-coat,C`, placed just AFTER it (overlays draw in file order).
#   python tools/doll/p4_leather.py [--check]      (--check: exit 1 when a file is not as this tool writes it)
import os, re, sys
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FILES = [os.path.join(REPO, 'rpg', 'art', 'doll', 'maps', 'armour', b, f) for b in ('man', 'woman') for f in ('padded.pxm', 'padded_hang.pxm')]
FLAG = 'leather-coat'
BEGIN = '# ---- P4 LEATHER COAT (generated by tools/doll/p4_leather.py: do not edit by hand)'
END = '# ---- P4 LEATHER COAT end'
COAT = {'5': 'g', '6': 'g', '7': 'h', '8': 'i', '9': 'j'}
LEATHER = 'fghij'
DARKER = {'j': 'i', 'i': 'h', 'h': 'g', 'g': 'g', 'f': 'f'}
SLIT = 'g'


def lace_chars(woman):
    # (lit crossing, mid crossing): rawhide in cloth3. The man's files map 7 / 8 to cloth3 2 / 3 (their own legend); the
    # woman's files map 5-9 to linen and use only `person`, so the tail block adds D / Q (cloth3 3 / 2: woman.legend's D)
    return ('D', 'Q') if woman else ('8', '7')


def strip(lines):
    out, skip = [], False
    for ln in lines:
        if ln.strip() == BEGIN: skip = True; continue
        if ln.strip() == END: skip = False; continue
        if not skip: out.append(ln)
    return out


def parse(lines):
    """[(kind, lines)]: kind 'text' for anything outside a view, 'view' for a view block (its header, grid and sections up
    to the next blank line / view / comment line)."""
    blocks, i = [], 0
    while i < len(lines):
        if lines[i].startswith('view '):
            j = i + 1
            while j < len(lines) and lines[j].strip() != '' and not lines[j].startswith('view ') and not lines[j].startswith('#'):
                j += 1
            blocks.append(('view', lines[i:j]))
            i = j
        else:
            blocks.append(('text', [lines[i]]))
            i += 1
    return blocks


def header(h):
    """(tokens, cond, replace) of a view header."""
    t = h.split()
    cond, rep = None, False
    if 'when' in t:
        k = t.index('when')
        cond = t[k + 1]
        rep = k + 2 < len(t) and t[k + 2] == 'replace'
    return t, cond, rep


def new_header(h):
    t, cond, rep = header(h)
    if cond is None:
        k = t.index('stretch') if 'stretch' in t else len(t)
        t = t[:k] + ['when', FLAG, 'replace'] + t[k:]
    else:
        k = t.index('when')
        t[k + 1] = FLAG + ',' + cond
    return ' '.join(t)


def recut(view, woman):
    h = view[0]
    t, cond, rep = header(h)
    facing, key = t[1], (t[t.index('key') + 1] if 'key' in t else 'rest')
    grid, rest, i = [], [], 1
    while i < len(view) and view[i].startswith('|'):
        grid.append(view[i][1:]); i += 1
    rest = view[i:]
    rows = [list(r) for r in grid]
    coat = lambda c: c in COAT
    n = len(rows)
    # the belt: a row under the first whose leather outnumbers its coat (the collar row 0 and the last row, the hem, never)
    belt = -1
    for y in range(1, n - 1):
        lc = sum(1 for c in rows[y] if c in LEATHER)
        cc = sum(1 for c in rows[y] if coat(c))
        if lc >= 3 and lc > cc:
            belt = y
            break
    out = [[COAT.get(c, c) for c in r] for r in rows]
    if belt >= 0:
        out[belt] = [DARKER[c] if c in DARKER else c for c in out[belt]]
    lit, mid = lace_chars(woman)
    laces = []   # (P5 MARKS, decision 2) the crossings' cells: N in the region plane, so a maker's coat laces in its dye
    is_overlay = cond is not None and not rep
    if belt > 1 and key != 'lie' and not is_overlay and 'hang' not in os.path.basename(CUR):
        if facing == 'D':
            # the centre two columns of the body rows (the coat's span on the row under the collar)
            xs = [x for x, c in enumerate(rows[1]) if coat(c)]
            if len(xs) >= 6:
                cx = (xs[0] + xs[-1] + 1) // 2   # the right of the two centre columns
                for y in range(1, belt):
                    if not (coat(rows[y][cx - 1]) and coat(rows[y][cx])): continue
                    a = (y % 2) == 1
                    out[y][cx - 1] = lit if a else SLIT
                    out[y][cx] = SLIT if a else mid
                    laces.append((cx - 1, y) if a else (cx, y))
        elif facing in ('R', 'L'):
            # the lace eyes one pixel inside the front edge (R: the right, L: the left), every other row
            for y in range(1, belt):
                xs = [x for x, c in enumerate(rows[y]) if coat(c)]
                if len(xs) < 4: continue
                x = xs[-2] if facing == 'R' else xs[1]
                out[y][x] = (lit if facing == 'R' else mid) if (y % 2) == 1 else SLIT
                if (y % 2) == 1: laces.append((x, y))
    return [new_header(h)] + ['|' + ''.join(r) for r in out] + lace_regions(rest, laces)


def lace_regions(rest, laces):
    """(P5 MARKS, FIX_BATCH_P5 3.3 / decision 2) the lace crossings take N in the view's region plane (only a view that
    has one, only where the plane is '.'): the doll draws N in the maker people's dye band, a maker-less coat (no
    fingerprint) keeps the rawhide. Pixels unchanged."""
    if not laces or 'regions' not in [r.strip() for r in rest]: return rest
    out = list(rest)
    k = [r.strip() for r in out].index('regions') + 1
    for x, y in laces:
        i = k + y
        if i >= len(out) or not out[i].startswith('|'): continue
        row = list(out[i][1:])
        while len(row) <= x: row.append('.')
        if row[x] == '.': row[x] = 'N'
        out[i] = '|' + ''.join(row)
    return out


def generate(path):
    global CUR
    CUR = path
    woman = os.sep + 'woman' + os.sep in path
    src = open(path, encoding='utf-8').read().split('\n')
    lines = strip(src)
    blocks = parse(lines)
    out, tail = [], []
    for kind, bl in blocks:
        if kind == 'text':
            out.extend(bl); continue
        _, cond, rep = header(bl[0])
        cut = recut(bl, woman)
        if cond is None:
            out.extend(bl)
            tail.append(cut)
        elif rep:
            out.extend([BEGIN] + cut + [END])
            out.extend(bl)
        else:
            out.extend(bl)
            out.extend([BEGIN] + cut + [END])
    while out and out[-1] == '': out.pop()
    out.append('')
    out.append(BEGIN)
    if woman: out.extend(['legend D cloth3 3', 'legend Q cloth3 2', ''])
    for k, cut in enumerate(tail):
        if k: out.append('')
        out.extend(cut)
    out.append(END)
    out.append('')
    return '\n'.join(out), '\n'.join(src)


CUR = ''
if __name__ == '__main__':
    check = '--check' in sys.argv
    bad = 0
    for f in FILES:
        new, old = generate(f)
        if new != old:
            if check:
                print('p4_leather: %s is not as generated' % os.path.relpath(f, REPO)); bad += 1
            else:
                open(f, 'w', encoding='utf-8', newline='\n').write(new)
                print('p4_leather: wrote %s' % os.path.relpath(f, REPO))
        else:
            print('p4_leather: %s up to date' % os.path.relpath(f, REPO))
    sys.exit(1 if bad else 0)
