#!/usr/bin/env python3
# tools/doll/p3_brig.py: (P3 ART, B10) the brigandine as a coat of plates. ARMOUR-M's brigandine (wave 2 r1) painted the coat
# in the maker's cloth with one rivet course a row: at 1x it read as cloth (a padded coat). This tool ADDS, to each base view
# of rpg/art/doll/maps/armour/{man,woman}/brigandine.pxm and brigandine_hang.pxm (never touching a drawn view), a
# `when brig-plates replace` view with the SAME mask, origin, regions and build row (no outline, fit or bulk change: the
# owner's T1-T2 "simple, not bulky"), its pixels re-cut from the base by rule:
#   - each rivet course (a row with metal-2 rivet heads among the coat's cloth) and the row under it become a course of
#     plates in the METAL ramp (lit p -> y, base o -> x, shadow n -> w; the seams and the outline m stay the dark cloth), the
#     rivet heads metal highlights (P -> z, O -> y);
#   - every other row of coat cloth is darkened a step (p -> o, o -> n): the cloth behind the plates;
#   - the shoulder row (the first coat row under the gorget) takes metal at both edges (v y ... w v);
#   - the gorget, the belt and its buckle, linen, cloak and device pixels are kept.
# The resolver flags `brig-plates` on every brigandine; the T5 / T6 / Mythic `when` views come first in each file, so they
# still win there (only T1-T4 change). Re-run after a change to the base views:
#   python tools/doll/p3_brig.py [--check]
import os, re, sys
REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FILES = [os.path.join(REPO, 'rpg', 'art', 'doll', 'maps', 'armour', b, f) for b in ('man', 'woman') for f in ('brigandine.pxm', 'brigandine_hang.pxm')]
FLAG = 'brig-plates'
BEGIN, END = '# ---- P3 COAT OF PLATES (generated by tools/doll/p3_brig.py: do not edit by hand)', '# ---- P3 COAT OF PLATES end'
ACCENT = set('mnop')
PLATE = {'p': 'y', 'o': 'x', 'n': 'w', 'P': 'z', 'O': 'y'}
CLOTH = {'p': 'o', 'o': 'n'}


def recut(rows):
    out = [list(r) for r in rows]
    course = [any(c in 'PO' for c in r) and any(c in ACCENT for c in r) for r in rows]
    plate = [course[i] or (i > 0 and course[i - 1] and any(c in ACCENT for c in rows[i])) for i in range(len(rows))]
    for i, r in enumerate(rows):
        for j, c in enumerate(r):
            if plate[i]:
                if c in PLATE: out[i][j] = PLATE[c]
            elif c in CLOTH:
                out[i][j] = CLOTH[c]
    # the shoulder row: the first coat row under a metal (gorget) row
    for i in range(1, len(rows)):
        if any(c in ACCENT for c in rows[i]) and any(c in 'vwxyz' for c in rows[i - 1]):
            cols = [j for j, c in enumerate(rows[i]) if c in ACCENT]
            if len(cols) >= 6:
                l, r = cols[0], cols[-1]
                out[i][l] = 'v'; out[i][r] = 'v'
                if rows[i][l + 1] in ACCENT: out[i][l + 1] = 'y'
                if rows[i][r - 1] in ACCENT: out[i][r - 1] = 'w'
            break
    return [''.join(r) for r in out]


def views(text):
    """the base views: (header line, [lines of the block]) for every `view` line without `when`"""
    lines = text.split('\n'); res = []; i = 0
    while i < len(lines):
        l = lines[i]
        if l.startswith('view ') and ' when ' not in l:
            j = i + 1
            while j < len(lines) and lines[j].strip() and not lines[j].startswith('view ') and not lines[j].startswith('# '):
                j += 1
            res.append((l, lines[i + 1:j]))
            i = j
        else:
            i += 1
    return res


def block(text):
    out = [BEGIN, '# (P3 ART, B10) the coat of plates (T1-T4): see tools/doll/p3_brig.py; the views above are ARMOUR-M\'s, kept.']
    for head, body in views(text):
        grid, rest, k = [], [], 0
        while k < len(body) and body[k].startswith('|'): grid.append(body[k][1:]); k += 1
        rest = body[k:]
        out.append(f'{head} when {FLAG} replace')
        out += ['|' + r for r in recut(grid)] + rest + ['']
    out.append(END)
    return '\n'.join(out)


def main():
    changed = 0
    for f in FILES:
        s = open(f, encoding='utf-8').read()
        base = s[:s.index(BEGIN)].rstrip('\n') if BEGIN in s else s.rstrip('\n')
        new = base + '\n\n' + block(base) + '\n'
        if new != s:
            changed += 1
            if '--check' not in sys.argv: open(f, 'w', encoding='utf-8', newline='\n').write(new)
    if '--check' in sys.argv: sys.exit(1 if changed else 0)
    print(f'p3_brig: {changed} file(s) written')


if __name__ == '__main__':
    main()
