// M12 "Rise and Fall": archetypes of realms that rise and fall, cast from the living sim (VISION_PLAN 15.20, 15.9,
// 15.33). REALM lane. The template markup and role conventions: rpg/story/saga.h. Each is told where the realm's facts
// hold (a kingdom and its ruler, a rival, a war, a camp in the hills, a ruin with a true record) and leaves the world
// changed by the choice the player makes.
//
//   warlord_tithe      THE WARLORD'S TITHE         a warband in the hills demands a sack from every door
//   sealed_will        THE SEALED WILL             the old ruler's last word on the succession, in the player's hands
//   pretender          THE PRETENDER'S RING        a stranger claims the blood of the old house; a ring in a ruin
//   regent_ledger      THE REGENT'S LEDGER         the steward of a young ruler keeps two sets of books
//   house_exile        THE LAST OF THE HOUSE       the last of a fallen house wants to come home to its ruin
//   last_garrison      THE LAST LOYAL GARRISON     soldiers who never heard the war was lost still hold an old fort
//   resettlers_road    THE RESETTLERS' ROAD        families going back to a dead village, and what they find there
//   hostage_heir       THE HOSTAGE HEIR            a rival's heir held to keep a treaty, and a plan to bring them home
//   broken_oath        THE BROKEN OATH             a lord sworn to the crown wants out of his oath
//   bleeding_tribute   THE TRIBUTE THAT BLEEDS     the tribute to a stronger realm takes the seed corn
//   call_to_arms       THE CALL TO ARMS            the crown summons the village's sons to an ally's war
//   hidden_banner      THE BANNER UNDER THE FLOOR  the old realm's banner, kept hidden under a new master
