// P1 "Fresh Roads": single stories that begin where the player stumbles on them rather than where someone asks: the
// words of a ruin (hook ruin: read a journal, a slab, a mural and a story begins) and the news of the realm reaching a
// village (hook event <type>: a price rise, a broken treaty, strangers from a newly met realm, a festival, a failed
// harvest, a first caravan). STORY lane. The template markup and role conventions: rpg/story/saga.h.
//
// A ruin story's giver and home are the ruin itself (a place: never talked to); it leads to the living in a settlement
// near. An event story's giver is the village (a place); its people are met there. Neither has twist slots: a ruin's
// {HOME} is no hamlet a twist's road could lead home to, and the news stories are short and local.
//
//   ruin_confession   THE DESERTER'S CONFESSION   a sentry's confession: he slept the night a village burned, and is
//                                                 sung as its hero
//   ruin_toll_silver  THE TOLL-KEEPER'S HOARD     a toll-keeper's map to the silver he skimmed from a town's bridge
//   ruin_letter       THE LETTER NEVER SENT       a soldier's love letter, sixty years late, to a woman still living
//   ruin_unrested     THE NAME THAT WANTS SAYING  a keep's last lord cannot rest until a temple says his name; he was
//                                                 a hard man
//   ruin_seed         THE LAST OF THE RED WHEAT   a sealed jar of a lost seed, and who should have it
//   ruin_warden_key   THE WARDEN'S KEY            the key to a vault the warden locked on the dead, and what to do with it
//   ev_salt_price     THE PRICE OF SALT           prices rose; the salter hoards before the winter's curing
//   ev_stranded       THE STRANDED PEDLAR         trade broken with a neighbour; one of their pedlars is stuck here
//   ev_strange_gift   THE STRANGERS' GIFT         envoys of a newly met people left a gift; the priest calls it a curse
//   ev_festival_bout  THE FESTIVAL CHAMPION       a festival bout is bought; the young challenger does not know
//   ev_gleaners       THE GLEANERS' FIELD         the harvest failed; the landholder forbids the poor to glean
//   ev_first_caravan  THE FIRST CARAVAN           a trade deal brings a caravan; the old carter it ruins means to stop it
